/** Merge a brief with the project's brand and accent into the renderer's flat string brief. */
export function rendererBrief(
  brief: MotionBrief,
  brand: string,
  accent: string,
  artwork?: string,
): Record<string, string> {
  const { artworkIndex: _unused, ...fields } = brief;
  void _unused;
  return { brand, accent, ...fields, ...(artwork ? { artwork } : {}) };
}
